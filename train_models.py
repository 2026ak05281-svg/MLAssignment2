"""
Train 5 classification models on the Telco Customer Churn dataset and persist
the fitted pipelines plus evaluation metrics for the Streamlit app.

Run:  python train_models.py
"""

import json
import os
import shutil
import time

import joblib
import numpy as np
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.calibration import CalibratedClassifierCV
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    f1_score,
    matthews_corrcoef,
    precision_score,
    recall_score,
    roc_auc_score,
    roc_curve,
)
from sklearn.model_selection import train_test_split
from sklearn.naive_bayes import GaussianNB
from sklearn.neighbors import KNeighborsClassifier
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.svm import SVC
from sklearn.tree import DecisionTreeClassifier

BASE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(BASE, 'data', 'telco_churn.csv')
MODELS = os.path.join(BASE, 'model')
TEST_CSV = os.path.join(BASE, 'test_data.csv')
os.makedirs(MODELS, exist_ok=True)

RANDOM_STATE = 42
TEST_SIZE = 0.2


def load_and_clean():
    df = pd.read_csv(DATA)

    # TotalCharges ships as text: 11 brand-new customers (tenure=0) have a blank
    # string, which forces the whole column to object dtype.
    n_blank = pd.to_numeric(df['TotalCharges'], errors='coerce').isna().sum()
    df['TotalCharges'] = pd.to_numeric(df['TotalCharges'], errors='coerce')
    df['TotalCharges'] = df['TotalCharges'].fillna(0.0)

    df = df.drop_duplicates().reset_index(drop=True)

    y = (df['Churn'] == 'Yes').astype(int)
    X = df.drop(columns='Churn')
    return X, y, n_blank


def build_preprocessor(X):
    numeric = X.select_dtypes(include=['int64', 'float64']).columns.tolist()
    categorical = [c for c in X.columns if c not in numeric]
    pre = ColumnTransformer([
        ('num', StandardScaler(), numeric),
        ('cat', OneHotEncoder(handle_unknown='ignore', drop='first'), categorical),
    ])
    return pre, numeric, categorical


def get_models():
    # SVC has no native predict_proba; CalibratedClassifierCV supplies the
    # probabilities that AUC needs (replaces the deprecated probability=True).
    svm = CalibratedClassifierCV(
        SVC(kernel='rbf', random_state=RANDOM_STATE), ensemble=False, cv=3)
    return {
        'Logistic Regression': LogisticRegression(max_iter=2000, random_state=RANDOM_STATE),
        'Decision Tree': DecisionTreeClassifier(max_depth=6, random_state=RANDOM_STATE),
        'K-Nearest Neighbors': KNeighborsClassifier(n_neighbors=21),
        'Naive Bayes (Gaussian)': GaussianNB(),
        'Support Vector Machine': svm,
    }


def write_model_readme(results, numeric, categorical, pre_fitted):
    """Describe every artifact in model/ so the folder explains itself."""
    rows = '\n'.join(
        f"| `{n.lower().replace(' ', '_').replace('(', '').replace(')', '').replace('-', '_')}.joblib` "
        f"| {n} | {r['Accuracy']:.4f} | {r['MCC Score']:.4f} |"
        for n, r in results.items())

    content = f"""# model/ — Trained Models, Preprocessing Artifacts and Source Code

Generated by `train_models.py`. Do not edit by hand; re-run the script instead.

## Saved trained models

Each `.joblib` holds a complete scikit-learn `Pipeline`:
`ColumnTransformer` (fitted `StandardScaler` + fitted `OneHotEncoder`) → classifier.
Loading one gives a ready-to-use model — no preprocessing needs to be reapplied.

| File | Classifier | Accuracy | MCC |
|---|---|---|---|
{rows}

## Preprocessing artifacts

| File | Contents |
|---|---|
| `preprocessor.joblib` | The standalone fitted `ColumnTransformer` — `StandardScaler` over {len(numeric)} numeric columns and `OneHotEncoder(drop='first')` over {len(categorical)} categorical columns. The same object is embedded in each pipeline above; it is saved separately so the fitted scaler statistics and encoder categories can be inspected or reused independently. |
| `metrics.json` | Evaluation metrics for all five models, ROC curve points, the input-column schema (types, ranges, allowed category values) and the dataset/split summary. Consumed by `app.py`. |

**Numeric columns ({len(numeric)}):** {', '.join(f'`{c}`' for c in numeric)}

**Categorical columns ({len(categorical)}):** {', '.join(f'`{c}`' for c in categorical)}

## Source code

| File | Purpose |
|---|---|
| `train_models.py` | Exact copy of the script that produced every artifact here — loads and cleans the data, builds the preprocessing pipeline, trains the five classifiers, evaluates them and writes this folder. |

Further source code lives in the repository root:

- `../train_models.py` — canonical copy of the above
- `../app.py` — Streamlit application that loads these models
- `../notebook/Telco_Churn_Classification.ipynb` — full analysis notebook

## Regenerating

```bash
python train_models.py
```

Rewrites every file in this folder plus `../test_data.csv`.
Fixed `random_state=42` makes the output reproducible.
"""
    with open(os.path.join(MODELS, 'README.md'), 'w', encoding='utf-8') as f:
        f.write(content)


def main():
    print('=' * 70)
    print('TELCO CHURN -- TRAINING 5 CLASSIFIERS')
    print('=' * 70)

    X, y, n_blank = load_and_clean()
    print(f'Rows {len(X)}   Features {X.shape[1]}   '
          f'Churn rate {y.mean():.1%}   (TotalCharges blanks repaired: {n_blank})')

    X_tr, X_te, y_tr, y_te = train_test_split(
        X, y, test_size=TEST_SIZE, random_state=RANDOM_STATE, stratify=y)
    print(f'Train {len(X_tr)}   Test {len(X_te)}')

    pre, numeric, categorical = build_preprocessor(X)
    print(f'Numeric cols {len(numeric)}   Categorical cols {len(categorical)}')

    # Standalone preprocessing artifact. The same transformer is also embedded in
    # every pipeline below; saving it separately makes the fitted scaler and
    # encoder inspectable and reusable on their own.
    pre_fitted = build_preprocessor(X)[0].fit(X_tr)
    joblib.dump(pre_fitted, os.path.join(MODELS, 'preprocessor.joblib'))
    print(f'Preprocessor saved -> {X.shape[1]} raw features '
          f'become {pre_fitted.transform(X_tr).shape[1]} encoded columns')

    results = {}
    roc_data = {}

    for name, clf in get_models().items():
        t0 = time.time()
        pipe = Pipeline([('pre', pre), ('clf', clf)])
        pipe.fit(X_tr, y_tr)

        y_pred = pipe.predict(X_te)
        y_proba = pipe.predict_proba(X_te)[:, 1]

        results[name] = {
            'Accuracy': accuracy_score(y_te, y_pred),
            'AUC Score': roc_auc_score(y_te, y_proba),
            'Precision': precision_score(y_te, y_pred, zero_division=0),
            'Recall': recall_score(y_te, y_pred, zero_division=0),
            'F1 Score': f1_score(y_te, y_pred, zero_division=0),
            'MCC Score': matthews_corrcoef(y_te, y_pred),
            'train_seconds': round(time.time() - t0, 2),
            'confusion_matrix': confusion_matrix(y_te, y_pred).tolist(),
        }

        fpr, tpr, _ = roc_curve(y_te, y_proba)
        roc_data[name] = {'fpr': fpr.tolist(), 'tpr': tpr.tolist()}

        slug = name.lower().replace(' ', '_').replace('(', '').replace(')', '').replace('-', '_')
        joblib.dump(pipe, os.path.join(MODELS, f'{slug}.joblib'))

        r = results[name]
        print(f'{name:26s} acc={r["Accuracy"]:.4f} auc={r["AUC Score"]:.4f} '
              f'prec={r["Precision"]:.4f} rec={r["Recall"]:.4f} '
              f'f1={r["F1 Score"]:.4f} mcc={r["MCC Score"]:.4f} '
              f'({r["train_seconds"]}s)')

    # Column metadata drives the app's prediction form.
    schema = {}
    for c in X.columns:
        if c in numeric:
            schema[c] = {'type': 'numeric',
                         'min': float(X[c].min()),
                         'max': float(X[c].max()),
                         'median': float(X[c].median())}
        else:
            schema[c] = {'type': 'categorical',
                         'options': sorted(X[c].dropna().astype(str).unique().tolist())}

    payload = {
        'results': results,
        'roc': roc_data,
        'schema': schema,
        'dataset': {
            'rows': int(len(X)),
            'features': int(X.shape[1]),
            'churn_rate': float(y.mean()),
            'train_rows': int(len(X_tr)),
            'test_rows': int(len(X_te)),
            'numeric_cols': numeric,
            'categorical_cols': categorical,
        },
    }
    with open(os.path.join(MODELS, 'metrics.json'), 'w') as f:
        json.dump(payload, f, indent=2)

    # Held-out test set shipped with the repo so the app has something to score
    # out of the box. Target written back as Yes/No to mirror the source file.
    test_out = X_te.copy()
    test_out['Churn'] = np.where(y_te.values == 1, 'Yes', 'No')
    test_out.to_csv(TEST_CSV, index=False)
    print(f'test_data.csv written: {len(test_out)} rows '
          f'({(test_out["Churn"] == "Yes").mean():.1%} churn)')

    # Ship the exact script that produced these artifacts alongside them, so the
    # model folder is self-contained and the copy can never drift.
    shutil.copyfile(os.path.abspath(__file__),
                    os.path.join(MODELS, 'train_models.py'))
    write_model_readme(results, numeric, categorical, pre_fitted)

    print(f'\nArtifacts written to {MODELS}')
    best = max(results, key=lambda k: results[k]['MCC Score'])
    print(f'Best by MCC: {best} ({results[best]["MCC Score"]:.4f})')


if __name__ == '__main__':
    main()
